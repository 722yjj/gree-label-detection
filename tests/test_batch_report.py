def _tmp_dir():
    root = Path(__file__).resolve().parent / ".tmp" / uuid.uuid4().hex
    root.mkdir(parents=True, exist_ok=True)
    return root


def _make_record(tmp: Path, code: str, case_id: str, *, verdict: str = "✅ 一致") -> CaseRunRecord:
    """Create a CaseRunRecord with minimal on-disk files."""
    case_dir = tmp / "results" / code / case_id
    case_dir.mkdir(parents=True, exist_ok=True)

    template_path = tmp / "templates" / f"{code}.jpg"
    target_path = tmp / "targets" / f"{code}_1.jpg"
    template_path.parent.mkdir(parents=True, exist_ok=True)
    target_path.parent.mkdir(parents=True, exist_ok=True)

    # Use a real small JPEG so openpyxl can load it
    try:
        import cv2  # noqa: F811
        img = np.zeros((20, 30, 3), dtype=np.uint8)
        cv2.imwrite(str(template_path), img)
        cv2.imwrite(str(target_path), img)
    except ImportError:
        template_path.write_bytes(_TINY_JPEG)
        target_path.write_bytes(_TINY_JPEG)

    vis_path = case_dir / "visualization_diff.jpg"
    try:
        import cv2
        cv2.imwrite(str(vis_path), np.zeros((20, 30, 3), dtype=np.uint8))
    except ImportError:
        vis_path.write_bytes(_TINY_JPEG)

    result_json_path = case_dir / "result.json"
    result_json_path.write_text(
        json.dumps({"success": True, "verdict": verdict}, ensure_ascii=False),
        encoding="utf-8",
    )

    return CaseRunRecord(
        code=code,
        case_id=case_id,
        template_path=str(template_path),
        target_path=str(target_path),
        result_json=str(result_json_path),
        visualization_diff=str(vis_path),
        success=True,
        skipped=False,
        verdict=verdict,
        error=None,
        duration_seconds=1.5,
    )


def test_generates_xlsx_with_correct_rows():
    tmp = _tmp_dir()
    try:
        output_dir = tmp / "results"
        output_dir.mkdir(parents=True, exist_ok=True)

        records = [
            _make_record(tmp, "600004075219", "600004075219__vs__600004075219_1"),
            _make_record(
                tmp,
                "600004075219",
                "600004075219__vs__600004075219_2",
                verdict="❌ 差异",
            ),
        ]

        from label_detection.batch_report import generate_batch_excel_report

        report_path = generate_batch_excel_report(output_dir, records)

        assert report_path.exists()
        assert report_path.suffix == ".xlsx"

        from openpyxl import load_workbook

        wb = load_workbook(str(report_path))
        ws = wb.active
        assert ws.title == "对比报告"
        # Header (row 1) + 2 data rows
        assert ws.max_row >= 3
        # Check header content
        assert ws.cell(row=1, column=1).value == "编号"
        assert ws.cell(row=1, column=3).value == "模板图"
        assert ws.cell(row=1, column=6).value == "判定"
        # Check data
        assert ws.cell(row=2, column=1).value == "600004075219"
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


